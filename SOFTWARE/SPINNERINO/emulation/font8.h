static inline int char_to_idx(char c) {
  if (c >= 'A' && c <= 'Z') return c - 'A';
  if (c >= 'a' && c <= 'z') return c - 'a';
  if (c >= '0' && c <= '9') return 26 + (c - '0');
  switch (c) {
    case ' ': return 36;
    case '/': return 37;
    case ':': return 38;
    case '<': return 39;
    case '>': return 40;
    case '!': return 41;
    case '.': return 42;
    case '-': return 43;
    case '_': return 44;
  }
  return 36;
}
