static const int DL_FRAMEFILE_N =
    (int)(sizeof(DL_FRAMEFILE) / sizeof(DL_FRAMEFILE[0]));

// Indice della voce che contiene 'ldframe' (o la piu' vicina sotto;
// -1 se il frame precede la prima voce). Lista ordinata per ld_start.
static inline int dl_framefile_find(int ldframe)
{
    int best = -1;
    for (int i = 0; i < DL_FRAMEFILE_N; i++) {
        if (DL_FRAMEFILE[i].ld_start <= ldframe) best = i;
        else break;
    }
    return best;
}
