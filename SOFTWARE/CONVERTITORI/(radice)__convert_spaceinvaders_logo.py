"""
Convert Space Invaders logo images to C header files for Galagino
- TFT: 224x96 RLE-compressed RGB565 byte-swapped
- OLED: 128x64 monochrome 1bpp (XBM format, swap=yes)

Usage:
  python convert_spaceinvaders_logo.py

Expects in parent directory:
  "space invaders ftf.png"  -> TFT logo
  "space invaders oled.png" -> OLED logo
"""

import os
import sys

try:
    from PIL import Image
except ImportError:
    print("ERROR: Pillow library required. Install with: pip install Pillow")
    sys.exit(1)

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(SCRIPT_DIR)
PARENT_DIR = os.path.dirname(PROJECT_DIR)
OUTPUT_DIR = os.path.join(PROJECT_DIR, "machines", "spaceinvaders")
LOGO_H = os.path.join(PROJECT_DIR, "logo.h")

# ─── RGB565 byte-swapped conversion ───
def rgb_to_rgb565_swapped(r, g, b):
    """Convert RGB888 to RGB565 byte-swapped for ESP32 SPI"""
    rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    # Byte-swap for ESP32 SPI
    return ((rgb565 & 0xFF) << 8) | ((rgb565 >> 8) & 0xFF)

# ─── TFT Logo: 224x96 canvas, image scaled to logo_w x logo_h centered ───
def convert_tft_logo(input_path, output_path):
    print(f"Converting TFT logo: {input_path}")
    img = Image.open(input_path).convert("RGB")

    # Full canvas is always 224x96 (required by menu renderer)
    # Logo image is scaled to logo_w x logo_h and centered (black borders)
    canvas_w, canvas_h = 224, 96
    logo_w, logo_h = 148, 58  # smaller to save flash space

    src_w, src_h = img.size
    # Auto-crop: remove black borders from source image first
    from PIL import ImageChops
    bg = Image.new("RGB", img.size, (0, 0, 0))
    diff = ImageChops.difference(img, bg)
    gray_diff = diff.convert("L")
    bbox = gray_diff.getbbox()
    if bbox:
        img = img.crop(bbox)
        src_w, src_h = img.size
        print(f"  Auto-cropped to: {src_w}x{src_h}")

    # Scale to COVER the logo area (fill logo_w x logo_h, may crop)
    scale = max(logo_w / src_w, logo_h / src_h)
    new_w = int(src_w * scale)
    new_h = int(src_h * scale)

    img_resized = img.resize((new_w, new_h), Image.LANCZOS)

    # Center-crop to logo size
    crop_x = (new_w - logo_w) // 2
    crop_y = (new_h - logo_h) // 2
    img_logo = img_resized.crop((crop_x, crop_y, crop_x + logo_w, crop_y + logo_h))

    # Place on black canvas
    canvas = Image.new("RGB", (canvas_w, canvas_h), (0, 0, 0))
    offset_x = (canvas_w - logo_w) // 2
    offset_y = (canvas_h - logo_h) // 2
    canvas.paste(img_logo, (offset_x, offset_y))

    # Convert all pixels to RGB565 byte-swapped
    pixels = []
    for y in range(canvas_h):
        for x in range(canvas_w):
            r, g, b = canvas.getpixel((x, y))
            pixels.append(rgb_to_rgb565_swapped(r, g, b))

    # RLE compression
    # Marker value = 1 (as used by other logos in menu.cpp)
    # Format: marker, count-1, color = run of 'count' pixels of 'color'
    #         (decoder does: pix += data[1] + 1, so we store count-1)
    #         literal_pixel = just the pixel value (if != marker)
    marker = 1
    rle = [marker]

    i = 0
    while i < len(pixels):
        # Count run of same pixel
        run_start = i
        while i < len(pixels) and pixels[i] == pixels[run_start] and (i - run_start) < 32767:
            i += 1
        run_len = i - run_start

        if run_len >= 3 or pixels[run_start] == marker:
            # Encode as RLE run: marker, count-1, color
            rle.append(marker)
            rle.append(run_len - 1)
            rle.append(pixels[run_start])
        else:
            # Encode as literal(s)
            for j in range(run_len):
                if pixels[run_start] == marker:
                    # Literal that equals marker: encode as run of 1 (marker, 0, color)
                    rle.append(marker)
                    rle.append(0)
                    rle.append(pixels[run_start])
                else:
                    rle.append(pixels[run_start])

    # Write C header
    with open(output_path, "w") as f:
        f.write(f"// Space Invaders TFT Logo - {canvas_w}x{canvas_h} ({logo_w}x{logo_h} centered) RLE-compressed RGB565 byte-swapped\n")
        f.write("// Auto-generated by convert_spaceinvaders_logo.py - DO NOT EDIT\n\n")
        f.write(f"const unsigned short spaceinvaders_logo[] = {{\n")

        for i in range(0, len(rle), 16):
            chunk = rle[i:i+16]
            line = ", ".join(str(v) for v in chunk)
            if i + 16 < len(rle):
                line += ","
            f.write(f"  {line}\n")

        f.write(f"}};\n")

    print(f"  Output: {output_path}")
    print(f"  RLE size: {len(rle)} words ({len(rle)*2} bytes)")
    print(f"  Compression: {len(rle)*2}/{canvas_w*canvas_h*2} = {100*len(rle)*2//(canvas_w*canvas_h*2)}%")

# ─── OLED Logo: 128x64, monochrome XBM ───
def convert_oled_logo(input_path):
    print(f"\nConverting OLED logo: {input_path}")
    img = Image.open(input_path).convert("RGBA")

    # Target size
    canvas_w, canvas_h = 128, 64

    # Resize maintaining aspect ratio
    src_w, src_h = img.size
    scale = min(canvas_w / src_w, canvas_h / src_h)
    new_w = int(src_w * scale)
    new_h = int(src_h * scale)

    img_resized = img.resize((new_w, new_h), Image.LANCZOS)

    # Create white canvas (OLED: 0xFF = white = background)
    canvas = Image.new("RGBA", (canvas_w, canvas_h), (255, 255, 255, 255))
    offset_x = (canvas_w - new_w) // 2
    offset_y = (canvas_h - new_h) // 2
    canvas.paste(img_resized, (offset_x, offset_y), img_resized if img_resized.mode == 'RGBA' else None)

    # Convert to grayscale
    gray = canvas.convert("L")

    # Threshold: dark pixels become logo (drawn), light pixels become background
    # For OLED in galagino: 0xFF bits = background (not drawn), 0x00 bits = drawn
    # Actually looking at the existing logos, 0xFF = all white background,
    # and drawXbm draws the 0 bits as pixels
    # So: light pixels -> 1 (background), dark pixels -> 0 (drawn)
    threshold = 128

    # Generate XBM data (H mode, 1 bit, swap=yes as per image2cpp settings)
    # Format: horizontal, MSB first with bit swap
    bytes_data = []
    for y in range(canvas_h):
        for x in range(0, canvas_w, 8):
            byte_val = 0
            for bit in range(8):
                px = x + bit
                if px < canvas_w:
                    pixel = gray.getpixel((px, y))
                    # In the existing logos, 0xFF = white background
                    # Pixel > threshold -> 1 (white/background)
                    # Pixel <= threshold -> 0 (black/drawn)
                    if pixel > threshold:
                        byte_val |= (1 << bit)  # swap mode: LSB first
                    # else: bit stays 0 (will be drawn as black on OLED)
            bytes_data.append(byte_val)

    # Verify size
    expected = canvas_w * canvas_h // 8
    assert len(bytes_data) == expected, f"Expected {expected} bytes, got {len(bytes_data)}"

    return bytes_data

def update_logo_h(oled_data):
    """Update logo.h with new OLED logo data"""
    print(f"\nUpdating logo.h: {LOGO_H}")

    with open(LOGO_H, "r") as f:
        content = f.read()

    # Find and replace the Space Invaders OLED logo section
    start_marker = "// Space Invaders OLED Logo"
    end_marker_candidates = ["\n// ", "\n#"]  # Next section or end of file

    start_idx = content.find(start_marker)
    if start_idx == -1:
        print("  ERROR: Could not find Space Invaders OLED logo section in logo.h")
        print("  Please manually replace the provisional logo data")
        # Write standalone file instead
        standalone = os.path.join(OUTPUT_DIR, "spaceinvaders_oled_logo.h")
        write_oled_standalone(oled_data, standalone)
        return

    # Find the end of the logo data (next section or end of array)
    end_idx = len(content)
    # Look for the closing }; of the array
    closing = content.find("};", start_idx)
    if closing != -1:
        end_idx = closing + 2

    # Generate new section
    new_section = generate_oled_section(oled_data)

    # Replace
    content = content[:start_idx] + new_section + content[end_idx:]

    with open(LOGO_H, "w") as f:
        f.write(content)

    print(f"  Updated SpaceInvaders_Logo_bits in logo.h ({len(oled_data)} bytes)")

def generate_oled_section(data):
    lines = []
    lines.append("// Space Invaders OLED Logo")
    lines.append("// Auto-generated by convert_spaceinvaders_logo.py")
    lines.append("#define SpaceInvaders_Logo_width 128")
    lines.append("#define SpaceInvaders_Logo_height 64")
    lines.append("const uint8_t SpaceInvaders_Logo_bits[] PROGMEM = {")

    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_str = ", ".join(f"0x{b:02X}" for b in chunk)
        if i + 16 < len(data):
            hex_str += ","
        lines.append(f"  {hex_str}")

    lines.append("};")
    return "\n".join(lines)

def write_oled_standalone(data, path):
    with open(path, "w") as f:
        f.write(generate_oled_section(data))
    print(f"  Written standalone: {path}")

def main():
    tft_path = os.path.join(PARENT_DIR, "space invaders ftf.png")
    oled_path = os.path.join(PARENT_DIR, "space invaders oled.png")
    tft_output = os.path.join(OUTPUT_DIR, "spaceinvaders_logo.h")

    if not os.path.exists(tft_path):
        print(f"WARNING: TFT logo not found: {tft_path}")
    else:
        convert_tft_logo(tft_path, tft_output)

    if not os.path.exists(oled_path):
        print(f"WARNING: OLED logo not found: {oled_path}")
    else:
        oled_data = convert_oled_logo(oled_path)
        update_logo_h(oled_data)

    print("\nDone!")

if __name__ == "__main__":
    main()
