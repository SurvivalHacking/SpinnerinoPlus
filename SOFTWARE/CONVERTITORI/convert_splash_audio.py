#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
convert_splash_audio.py — converte un file audio (MP3/WAV/OGG/FLAC...) nel
jingle dello splash per SPINNERINO P4.

Output: splash_audio.h (PCM signed 16-bit MONO @ 32000 Hz, embedded in flash)
        riprodotto da Audio::melody_render_buffer() via I2S ES8311.

Dipendenze: miniaudio (decodifica+resample senza ffmpeg), numpy.
    python -m pip install miniaudio numpy

Uso:
    python convert_splash_audio.py [input] [trim_start_s] [trim_end_s]
    (default: 03. ゲームスタート.mp3, nessun trim)
"""
import sys, os, array
import numpy as np
import miniaudio

SRC_DEFAULT = r"C:\Users\Tecnico\Downloads\03. ゲームスタート.mp3"
OUT = r"C:\Users\Tecnico\Desktop\PROGETTI SH\SPINNERINO\SPINNERINO NEW P4p\SPINNERINO\splash_audio.h"

RATE = 32000          # sample rate fisso del sistema audio (I2S)
PEAK = 0.88           # normalizzazione di picco (88% del fondo scala, headroom)
MAX_SECONDS = 8.0     # cap di sicurezza sulla durata (flash ~64KB/s mono)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SRC_DEFAULT
    t0  = float(sys.argv[2]) if len(sys.argv) > 2 else 0.0
    t1  = float(sys.argv[3]) if len(sys.argv) > 3 else None

    if not os.path.exists(src):
        print(f"!! file non trovato: {src}", file=sys.stderr); sys.exit(1)

    print(f"[convert_splash_audio] {src}")
    # decode_file non gestisce path non-ASCII su Windows (fopen) -> leggo i byte
    # e decodifico in memoria (miniaudio.decode auto-rileva il formato).
    with open(src, "rb") as fh:
        data = fh.read()
    dec = miniaudio.decode(data,
                           output_format=miniaudio.SampleFormat.SIGNED16,
                           nchannels=1, sample_rate=RATE)
    pcm = np.frombuffer(memoryview(dec.samples), dtype=np.int16).astype(np.float32)
    dur = len(pcm) / RATE
    print(f"  decodificato: {len(pcm)} sample, {dur:.2f}s mono @ {RATE} Hz")

    # Trim opzionale
    a = int(max(0.0, t0) * RATE)
    b = int(t1 * RATE) if t1 is not None else len(pcm)
    b = min(b, len(pcm))
    if a > 0 or b < len(pcm):
        pcm = pcm[a:b]
        print(f"  trim -> {len(pcm)/RATE:.2f}s")

    # Cap di sicurezza
    cap = int(MAX_SECONDS * RATE)
    if len(pcm) > cap:
        pcm = pcm[:cap]
        print(f"  cap a {MAX_SECONDS:.1f}s ({len(pcm)} sample)")

    # Normalizzazione di picco
    peak = float(np.max(np.abs(pcm))) if len(pcm) else 0.0
    if peak > 1.0:
        pcm = pcm * (PEAK * 32767.0 / peak)
    pcm = np.clip(np.round(pcm), -32768, 32767).astype(np.int16)

    n = len(pcm)
    kb = n * 2 / 1024.0
    print(f"  output: {n} sample, {n/RATE:.2f}s, ~{kb:.0f} KB flash")

    base = os.path.basename(src)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by convert_splash_audio.py - DO NOT EDIT\n")
        f.write(f"// Source: {base}\n")
        f.write("// Format: PCM signed 16-bit MONO @ 32000 Hz (I2S ES8311)\n")
        f.write("#ifndef _SPLASH_AUDIO_H_\n#define _SPLASH_AUDIO_H_\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define SPLASH_AUDIO_RATE 32000\n")
        f.write(f"#define SPLASH_AUDIO_LEN  {n}\n\n")
        f.write(f"const int16_t splash_audio[{n}] = {{\n")
        row = []
        for i, s in enumerate(pcm):
            row.append(str(int(s)))
            if len(row) == 16:
                f.write("  " + ",".join(row) + ",\n"); row = []
        if row:
            f.write("  " + ",".join(row) + ",\n")
        f.write("};\n\n#endif // _SPLASH_AUDIO_H_\n")

    print(f"  scritto {OUT}  ({os.path.getsize(OUT)/1024:.0f} KB sorgente)")
    print("Done!")


if __name__ == "__main__":
    main()
