import os as _os
__file__ = _os.path.abspath(_os.path.join(
    _os.path.dirname(_os.path.abspath(__file__)), "..", "SPINNERINO", "FILE ROMCONV PY",
    _os.path.basename(__file__)))
# --- fine blocco percorsi ---

"""
Convert MotoRace USA logo images to C header files for GALAGONE.
TFT logo: 224x96 RGB565 byte-swapped, RLE compressed
OLED logo: 128x64 XBM monochrome
"""

from PIL import Image, ImageEnhance
import os, sys

# Paths (sketch/FILE ROMCONV PY/ -> ../machines/motorace + ../../LOGHI/)
_HERE   = os.path.dirname(os.path.abspath(__file__))
_SKETCH = os.path.dirname(_HERE)
_LOGHI  = os.path.join(os.path.dirname(_SKETCH), "LOGHI")
TFT_IMG = os.path.join(_LOGHI, "motorace tft.jpg")     # se mancante, aggiungi in LOGHI/
OLED_IMG = os.path.join(_LOGHI, "motorace oled.jpg")
OUTDIR = os.path.join(_SKETCH, "machines", "motorace")
os.makedirs(OUTDIR, exist_ok=True)

def rgb_to_565_swap(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    val = (r5 << 11) | (g6 << 5) | b5
    return ((val & 0xFF) << 8) | ((val >> 8) & 0xFF)

def auto_crop(img):
    px = img.load()
    w, h = img.size
    bg = px[0, 0]
    x0, y0, x1, y1 = w, h, 0, 0
    threshold = 30
    for y in range(h):
        for x in range(w):
            p = px[x, y]
            if isinstance(p, tuple) and len(p) >= 3:
                diff = abs(p[0]-bg[0]) + abs(p[1]-bg[1]) + abs(p[2]-bg[2])
            elif isinstance(bg, tuple):
                diff = abs(p - bg[0])
            else:
                diff = abs(p - bg)
            if diff > threshold:
                x0 = min(x0, x)
                y0 = min(y0, y)
                x1 = max(x1, x)
                y1 = max(y1, y)
    if x1 > x0 and y1 > y0:
        return img.crop((x0, y0, x1+1, y1+1))
    return img

def rle_encode(pixels):
    used = set(pixels)
    marker = None
    for m in range(65536):
        if m not in used:
            marker = m
            break
    if marker is None:
        marker = 1

    encoded = [marker]
    i = 0
    while i < len(pixels):
        run = 1
        while i + run < len(pixels) and pixels[i + run] == pixels[i] and run < 256:
            run += 1
        if pixels[i] == marker:
            encoded.extend([marker, run - 1, pixels[i]])
            i += run
        elif run >= 3:
            encoded.extend([marker, run - 1, pixels[i]])
            i += run
        else:
            encoded.append(pixels[i])
            i += 1
    return encoded

# TFT Logo (224x96)
print("Converting TFT logo...")
img = Image.open(TFT_IMG).convert("RGB")
img = auto_crop(img)
w, h = img.size
scale = min(224 / w, 96 / h) * 0.70  # ridotto del 30%
new_w = int(w * scale)
new_h = int(h * scale)
img = img.resize((new_w, new_h), Image.LANCZOS)
canvas = Image.new("RGB", (224, 96), (0, 0, 0))
x_off = (224 - new_w) // 2
y_off = (96 - new_h) // 2
canvas.paste(img, (x_off, y_off))

pixels = []
for y in range(96):
    for x in range(224):
        r, g, b = canvas.getpixel((x, y))
        pixels.append(rgb_to_565_swap(r, g, b))

encoded = rle_encode(pixels)
print(f"  TFT: {224}x{96}, raw={len(pixels)*2} bytes, RLE={len(encoded)*2} bytes")

# Write TFT logo only (no OLED here)
with open(os.path.join(OUTDIR, "motorace_logo.h"), "w") as f:
    f.write("// MotoRace USA - TFT Logo (224x96, RGB565 byte-swapped, RLE)\n")
    f.write("// Auto-generated by convert_motorace_logo.py\n\n")
    f.write(f"const unsigned short motorace_logo[] PROGMEM = {{\n")
    for i in range(0, len(encoded), 12):
        chunk = encoded[i:i+12]
        f.write("  " + ", ".join(str(v) for v in chunk) + ",\n")
    f.write("};\n")
print("  Written motorace_logo.h (TFT only)")

# OLED Logo (128x64, XBM) - appended to logo.h
print("Converting OLED logo...")
img2 = Image.open(OLED_IMG).convert("RGB")
img2 = auto_crop(img2)
# Enhance contrast before converting to grayscale
enhancer = ImageEnhance.Contrast(img2)
img2 = enhancer.enhance(2.0)
img2_gray = img2.convert("L")

w, h = img2_gray.size
scale = min(128 / w, 64 / h)
new_w = int(w * scale)
new_h = int(h * scale)
img2_gray = img2_gray.resize((new_w, new_h), Image.LANCZOS)

canvas2 = Image.new("L", (128, 64), 0)
x_off = (128 - new_w) // 2
y_off = (64 - new_h) // 2
canvas2.paste(img2_gray, (x_off, y_off))

# Use lower threshold for this logo (text on dark bg)
xbm_bytes = []
for y in range(64):
    for x_byte in range(16):
        byte_val = 0
        for bit in range(8):
            px = canvas2.getpixel((x_byte * 8 + bit, y))
            if px > 60:  # lower threshold for text logos
                byte_val |= (1 << bit)
        xbm_bytes.append(byte_val)

print(f"  OLED: 128x64, {len(xbm_bytes)} bytes, non-zero: {sum(1 for b in xbm_bytes if b)}")

# Append to logo.h
LOGO_H = os.path.join(os.path.dirname(os.path.abspath(__file__)), "logo.h")
with open(LOGO_H, "a") as f:
    f.write("\n// MotoRace USA - OLED Logo (128x64, XBM)\n")
    f.write("#define Motorace_Logo_width 128\n")
    f.write("#define Motorace_Logo_height 64\n")
    f.write("const uint8_t Motorace_Logo_bits[] PROGMEM = {\n")
    for i in range(0, len(xbm_bytes), 16):
        chunk = xbm_bytes[i:i+16]
        f.write("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
    f.write("};\n")
print("  Appended OLED logo to logo.h")

print("\nDone!")
