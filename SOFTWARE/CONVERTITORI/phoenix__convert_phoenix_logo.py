#!/usr/bin/env python3
"""
Convert Phoenix logo images to C headers for GALAGINO menu (FULL28 / CYD).

Outputs:
  machines/phoenix/phoenix_logo.h       - TFT 224x96 RGB565 byte-swapped RLE
  machines/phoenix/phoenix_oled_logo.h  - OLED 128x64 XBM (PhoenixLogo_bits[])

Convention:
  - TFT logo: testo del PNG su sfondo nero (logo Phoenix verde su nero)
              ridotto al 80% per estetica (richiesta utente)
  - OLED logo: pixel non-neri del source = ON (bit 1, illuminati)
               pixel neri / scuri = OFF (bit 0, spenti) → invert=false in src.ino

Usage: python convert_phoenix_logo.py
Requires: Pillow (pip install Pillow)
"""

from PIL import Image
import os, sys

# ═══════════════════════════════════════════════════════
# CONFIGURATION
# ═══════════════════════════════════════════════════════
TFT_IMG_CANDIDATES = [
    r"C:\Users\Tecnico\Desktop\SPINNERINO\SPINNERINO NEW P4\LOGHI\phoenix tft.png",
    r"C:\Users\Tecnico\Desktop\SPINNERINO\SPINNERINO NEW P4\LOGHI\phoenix tft.jpeg",
    r"C:\Users\Tecnico\Desktop\GALAGINO PROGETTO ORIGINALE\phoenix tft.png",
    r"C:\Users\Tecnico\Desktop\GALAGINO PROGETTO ORIGINALE\phoenix logo.png",
]
OLED_IMG_CANDIDATES = [
    r"C:\Users\Tecnico\Desktop\GALAGINO PROGETTO ORIGINALE\phoenix oled.png",
    # Se non esiste OLED dedicato, useremo lo stesso PNG TFT come sorgente
    # (script auto-fallback a TFT_IMG con conversione B/W).
]
OUTDIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "machines", "phoenix")
os.makedirs(OUTDIR, exist_ok=True)

TFT_W, TFT_H   = 224, 96
OLED_W, OLED_H = 128, 64

TFT_SIZE_FACTOR = 0.80   # richiesta utente: logo ridotto del 20%

# ═══════════════════════════════════════════════════════
# Helpers
# ═══════════════════════════════════════════════════════
def find_first(paths):
    for p in paths:
        if os.path.exists(p):
            return p
    return None

def rgb_to_565_swap(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    val = (r5 << 11) | (g6 << 5) | b5
    return ((val & 0xFF) << 8) | ((val >> 8) & 0xFF)

def auto_crop(img):
    """Crop a uniform background (based on top-left pixel) off all 4 sides."""
    px = img.load()
    w, h = img.size
    bg = px[0, 0]
    if not isinstance(bg, tuple): bg = (bg, bg, bg)
    x0, y0, x1, y1 = w, h, 0, 0
    threshold = 40
    for y in range(h):
        for x in range(w):
            p = px[x, y]
            if not isinstance(p, tuple): p = (p, p, p)
            diff = abs(p[0]-bg[0]) + abs(p[1]-bg[1]) + abs(p[2]-bg[2])
            if diff > threshold:
                x0 = min(x0, x); y0 = min(y0, y)
                x1 = max(x1, x); y1 = max(y1, y)
    if x1 > x0 and y1 > y0:
        return img.crop((x0, y0, x1+1, y1+1))
    return img

def rle_encode(pixels):
    used = set(pixels)
    marker = next((m for m in range(65536) if m not in used), 1)
    encoded = [marker]
    i = 0
    while i < len(pixels):
        run = 1
        while i + run < len(pixels) and pixels[i + run] == pixels[i] and run < 256:
            run += 1
        if pixels[i] == marker or run >= 3:
            encoded.extend([marker, run - 1, pixels[i]])
            i += run
        else:
            encoded.append(pixels[i])
            i += 1
    return encoded

# ═══════════════════════════════════════════════════════
# 1. TFT logo (RGB565 byte-swapped RLE, 224x96 canvas, 80%)
# ═══════════════════════════════════════════════════════
print("=== TFT Logo ===")
TFT_IMG = find_first(TFT_IMG_CANDIDATES)
if not TFT_IMG:
    print("ERROR: TFT image not found. Cercato in:")
    for p in TFT_IMG_CANDIDATES: print(f"   {p}")
    sys.exit(1)
print(f"  Source: {TFT_IMG}")

img = Image.open(TFT_IMG).convert("RGB")
print(f"  Original size: {img.size}")
img = auto_crop(img)
print(f"  Auto-cropped: {img.size}")

# Letterbox 80% size in 224x96 canvas (richiesta utente: logo grande con margine)
iw, ih = img.size
scale = min(TFT_W / iw, TFT_H / ih) * TFT_SIZE_FACTOR
new_w, new_h = max(1, int(iw * scale)), max(1, int(ih * scale))
img = img.resize((new_w, new_h), Image.LANCZOS)
print(f"  Resized (80%): {img.size}")

BLACK_BG = (0, 0, 0)
canvas = Image.new("RGB", (TFT_W, TFT_H), BLACK_BG)
canvas.paste(img, ((TFT_W - new_w) // 2, (TFT_H - new_h) // 2))

pixels = []
for y in range(TFT_H):
    for x in range(TFT_W):
        r, g, b = canvas.getpixel((x, y))
        pixels.append(rgb_to_565_swap(r, g, b))

encoded = rle_encode(pixels)
print(f"  RLE: raw={len(pixels)*2}B -> compressed={len(encoded)*2}B")

outpath = os.path.join(OUTDIR, "phoenix_logo.h")
with open(outpath, "w") as f:
    f.write("// Phoenix - TFT Logo (224x96, RGB565 byte-swapped, RLE)\n")
    f.write("// Auto-generated by convert_phoenix_logo.py\n")
    f.write("// Logo ridotto al 80% (richiesta utente)\n\n")
    f.write("const unsigned short phoenix_logo[] PROGMEM = {\n")
    for i in range(0, len(encoded), 12):
        chunk = encoded[i:i+12]
        f.write("  " + ", ".join(str(v) for v in chunk) + ",\n")
    f.write("};\n")
print(f"  Written {outpath}")

# ═══════════════════════════════════════════════════════
# 2. OLED logo (XBM 128x64)
# Pixel non-nero del source = ON (bit 1, illuminato)
# Pixel nero/scuro = OFF (bit 0, spento)
# Auto-fallback: usa TFT_IMG come source se manca OLED dedicato.
# ═══════════════════════════════════════════════════════
print("\n=== OLED Logo ===")
OLED_IMG = find_first(OLED_IMG_CANDIDATES)
if not OLED_IMG:
    OLED_IMG = TFT_IMG
    print(f"  No OLED-specific image found, using TFT source: {OLED_IMG}")
else:
    print(f"  Source: {OLED_IMG}")

src = Image.open(OLED_IMG)
if src.mode in ("RGBA", "LA") or (src.mode == "P" and "transparency" in src.info):
    src = src.convert("RGBA")
    bg = Image.new("RGBA", src.size, (0, 0, 0, 255))   # composite su NERO
    oimg = Image.alpha_composite(bg, src).convert("RGB")
else:
    oimg = src.convert("RGB")
print(f"  Mode: {oimg.size} (orig {src.mode})")
oimg = auto_crop(oimg)
print(f"  Auto-cropped: {oimg.size}")

# Letterbox in 128x64, mantenendo aspect ratio
ow, oh = oimg.size
oscale = min(OLED_W / ow, OLED_H / oh)
nw, nh = max(1, int(ow * oscale)), max(1, int(oh * oscale))
oimg = oimg.resize((nw, nh), Image.LANCZOS)
canvas = Image.new("RGB", (OLED_W, OLED_H), (0, 0, 0))
canvas.paste(oimg, ((OLED_W - nw) // 2, (OLED_H - nh) // 2))
print(f"  Letterbox: {oimg.size} on {OLED_W}x{OLED_H}")

def pixel_is_on(r, g, b):
    """Pixel non-nero/scuro → ON (bit 1, illuminato). Background nero → OFF."""
    if r < 40 and g < 40 and b < 40:
        return False
    return True

# XBM encoding: 8 pixels per byte, LSB = leftmost pixel
bytes_per_row = OLED_W // 8
oled_bytes = []
for y in range(OLED_H):
    for bx in range(bytes_per_row):
        byte = 0
        for bit in range(8):
            x = bx * 8 + bit
            r, g, b = canvas.getpixel((x, y))
            if pixel_is_on(r, g, b):
                byte |= (1 << bit)
        oled_bytes.append(byte)

assert len(oled_bytes) == (OLED_W * OLED_H) // 8 == 1024

outpath = os.path.join(OUTDIR, "phoenix_oled_logo.h")
with open(outpath, "w") as f:
    f.write("// Phoenix - OLED Logo (128x64 XBM, LSB-first)\n")
    f.write("// Auto-generated by convert_phoenix_logo.py\n")
    f.write("// bit 1 = pixel ON (illuminato), bit 0 = pixel OFF (nero)\n\n")
    f.write("const uint8_t PhoenixLogo_bits[] PROGMEM = {\n")
    for i in range(0, len(oled_bytes), 16):
        chunk = oled_bytes[i:i+16]
        f.write("  " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n")
    f.write("};\n")
print(f"  Written {outpath}")
print("\nDone!")
print("  Ricorda di:")
print("   - #include machines/phoenix/phoenix_oled_logo.h da logo.h")
print("   - aggiungere case MCH_PHOENIX: bits = PhoenixLogo_bits; in src.ino")
