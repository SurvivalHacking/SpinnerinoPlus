#!/usr/bin/env python3
# convert_galagino_logos.py
# Converte i logo RLE del progetto Galagino V3 (Files_FULL28) nel formato
# RAW 224x96 usato da SPINNERINO P4 (BootMenu).
#
# Formato sorgente RLE:
#   logo[0]      = marker (sentinella, tipicamente 1)
#   logo[1..]    = stream:
#                    se v != marker -> singolo pixel di colore v
#                    se v == marker -> tripla (marker, count, color),
#                                      ripeti color per (count+1) volte
#
# Formato target RAW (SPINNERINO):
#   #define <GAME>_LOGO_W 224
#   #define <GAME>_LOGO_H 96
#   const unsigned short <game>_logo[224*96] PROGMEM = { ... };
#
# Uso:
#   python convert_galagino_logos.py <input_logo.h> <output_logo.h> <game_name>
#
# Esempio:
#   python convert_galagino_logos.py spaceinvaders_logo.h \
#          machines/spaceinvaders/spaceinvaders_logo.h spaceinvaders

import re
import sys
import os

LOGO_W = 224
LOGO_H = 96
TOTAL = LOGO_W * LOGO_H  # 21504


def parse_array(text):
    """Estrae i numeri dall'array C `xxx_logo[] = { 1, 2, 3, ... };`."""
    m = re.search(r'_logo\s*\[[^\]]*\]\s*(?:PROGMEM\s*)?=\s*\{(.*?)\}\s*;',
                  text, re.DOTALL)
    if not m:
        raise RuntimeError("Array logo non trovato nel file di input.")
    body = m.group(1)
    # Strip commenti // e /* */
    body = re.sub(r'//.*', '', body)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.DOTALL)
    nums = re.findall(r'-?\d+', body)
    if not nums:
        raise RuntimeError("Nessun numero nell'array.")
    return [int(n) & 0xFFFF for n in nums]  # mask a 16 bit


def decode_rle(values):
    """Decodifica RLE Galagino, ritorna lista di TOTAL pixel (16-bit)."""
    if len(values) < 2:
        raise RuntimeError("Stream RLE troppo corto.")
    marker = values[0]
    out = []
    i = 1
    while i < len(values) and len(out) < TOTAL:
        v = values[i]
        if v != marker:
            out.append(v)
            i += 1
        else:
            if i + 2 >= len(values):
                raise RuntimeError(
                    f"Tripla RLE incompleta a indice {i} (len={len(values)}).")
            count = values[i + 1]
            color = values[i + 2]
            run = count + 1
            out.extend([color] * run)
            i += 3
    if len(out) < TOTAL:
        raise RuntimeError(
            f"Decodifica corta: {len(out)} pixel su {TOTAL} attesi.")
    if len(out) > TOTAL:
        # Tronchiamo: alcuni encoder mettono un terminatore extra.
        out = out[:TOTAL]
    return out


def emit_raw(pixels, var_name):
    upper = var_name.upper()
    lines = [
        f"// Auto-generated by convert_galagino_logos.py",
        f"// {LOGO_W}x{LOGO_H} RGB565 byte-swap (ESP32 SPI BE), RAW format",
        f"#define {upper}_LOGO_W {LOGO_W}",
        f"#define {upper}_LOGO_H {LOGO_H}",
        f"const unsigned short {var_name}_logo[{LOGO_W}*{LOGO_H}] PROGMEM = {{",
    ]
    # 12 valori per riga, hex 4 cifre
    per_line = 12
    for r in range(0, TOTAL, per_line):
        chunk = pixels[r:r + per_line]
        lines.append(
            "  " + ", ".join(f"0x{p:04X}" for p in chunk) +
            ("," if r + per_line < TOTAL else "")
        )
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 4:
        print("uso: python convert_galagino_logos.py <input.h> <output.h> <game_name>")
        sys.exit(1)

    in_path = sys.argv[1]
    out_path = sys.argv[2]
    game = sys.argv[3]

    if not os.path.isfile(in_path):
        print(f"ERRORE: input non trovato: {in_path}")
        sys.exit(2)

    with open(in_path, 'r', encoding='utf-8', errors='replace') as f:
        text = f.read()

    values = parse_array(text)
    print(f"[INFO] {len(values)} valori RLE letti, marker = {values[0]}")

    pixels = decode_rle(values)
    print(f"[INFO] {len(pixels)} pixel decodificati ({LOGO_W}x{LOGO_H})")

    out_text = emit_raw(pixels, game)
    os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(out_text)
    print(f"[OK] scritto {out_path} ({os.path.getsize(out_path)} byte)")


if __name__ == '__main__':
    main()
