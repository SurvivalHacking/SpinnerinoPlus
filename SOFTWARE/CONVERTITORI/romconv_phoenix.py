#!/usr/bin/env python3
# romconv_phoenix.py
# Converte le ROM Phoenix (set "phoenix", Amstar/Centuri 1980) negli header
# .h usati dal porting SPINNERINO.
#
# Set MAME (mainset "phoenix") - 14 file totali:
#   ROM CPU 16 KB  : ic45..ic52 (8 × 2 KB)
#   GFX BG  4 KB   : ic23 (plane0) + ic24 (plane1)
#   GFX FG  4 KB   : ic39 (plane0) + ic40 (plane1)
#   PROM palette   : mmi6301.ic40 (R-G-B low) + mmi6301.ic41 (R-G-B high)
#
# Uso:
#   python romconv_phoenix.py <rom_dir> <output_dir>
#
# Es.:
#   python romconv_phoenix.py "ROM/phoenix_extracted" "SPINNERINO/machines/phoenix"

import os
import sys


def read(rom_dir, name):
    path = os.path.join(rom_dir, name)
    if not os.path.isfile(path):
        # fallback: cerca senza suffisso (es. ic45-pg1.1a vs ic45.bin)
        candidates = [n for n in os.listdir(rom_dir) if n.startswith(name.split("-")[0])]
        if candidates:
            path = os.path.join(rom_dir, candidates[0])
            print(f"[FALLBACK] {name} -> {os.path.basename(path)}")
        else:
            raise FileNotFoundError(f"{name} non trovato in {rom_dir}")
    with open(path, "rb") as f:
        return f.read()


def emit_byte_array(name, data, comment=""):
    lines = [
        "// Auto-generated by romconv_phoenix.py - DO NOT EDIT",
        f"// {comment}" if comment else "",
        f"const unsigned char {name}[{len(data)}] PROGMEM = {{",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in chunk) +
                     ("," if i + 16 < len(data) else ""))
    lines.append("};")
    lines.append("")
    return "\n".join(l for l in lines if l is not None)


def emit_word_array(name, words, comment=""):
    lines = [
        "// Auto-generated by romconv_phoenix.py - DO NOT EDIT",
        f"// {comment}" if comment else "",
        f"const unsigned short {name}[{len(words)}] PROGMEM = {{",
    ]
    for i in range(0, len(words), 12):
        chunk = words[i:i + 12]
        lines.append("  " + ", ".join(f"0x{w:04X}" for w in chunk) +
                     ("," if i + 12 < len(words) else ""))
    lines.append("};")
    lines.append("")
    return "\n".join(l for l in lines if l is not None)


def to_rgb565_swap(r, g, b):
    rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return ((rgb565 >> 8) | (rgb565 << 8)) & 0xFFFF


def decode_palette(prom_lo, prom_hi):
    """
    MAME phoenix_palette decode ESATTO (phoenix_v.cpp linee 39-47):
      shifts = {0, 2, 1, -1, 1, 0}   # R G B PROM_LO; R G B PROM_HI
      masks  = {0x01,0x01,0x01, 0x02,0x02,0x02}
    Decodifica:
      R bit 0 = (lo >> 0) & 1 = lo[0]
      G bit 0 = (lo >> 2) & 1 = lo[2]
      B bit 0 = (lo >> 1) & 1 = lo[1]
      R bit 1 = (hi << 1) & 2 = hi[0] in pos 1
      G bit 1 = (hi >> 1) & 2 = hi[2] in pos 1
      B bit 1 = (hi >> 0) & 2 = hi[1] in pos 1

    bitswap<7>(i, 6,5,1,0,4,3,2) sull'indice (bit 7 ignorato).
    OC + 270 ohm pulldown + 100 ohm pullup → 4 livelli ~ [0, 85, 170, 255].
    """
    # Resistor net Phoenix: pullup 270, pulldown 100, OC, R={270, 1}
    # Compute esatto: V varies tra 0 e 1.351V su Vcc=5V → norm 0..255
    #   bits=00 (entrambi attivi via OC bit=0): V~0 -> 0
    #   bits=01 (R[1]=1 ohm attivo): V~0 -> 0
    #   bits=10 (R[0]=270 attivo, R[1] inattivo): V=1.069V -> 202
    #   bits=11 (entrambi inattivi, solo pulldown): V=1.351V -> 255
    LEVELS = [0, 0, 202, 255]

    palette = []
    for i in range(256):
        # bitswap<7>(i, 6,5,1,0,4,3,2)
        b6 = (i >> 6) & 1
        b5 = (i >> 5) & 1
        b1 = (i >> 1) & 1
        b0 = (i >> 0) & 1
        b4 = (i >> 4) & 1
        b3 = (i >> 3) & 1
        b2 = (i >> 2) & 1
        col = (b6 << 6) | (b5 << 5) | (b1 << 4) | (b0 << 3) | \
              (b4 << 2) | (b3 << 1) | b2

        lo = prom_lo[col]
        hi = prom_hi[col]

        r_bits = ((lo >> 0) & 1) | (((hi >> 0) & 1) << 1)
        g_bits = ((lo >> 2) & 1) | (((hi >> 2) & 1) << 1)  # G bit 1 da hi[2]
        b_bits = ((lo >> 1) & 1) | (((hi >> 1) & 1) << 1)  # B bit 1 da hi[1]

        r = LEVELS[r_bits]
        g = LEVELS[g_bits]
        b = LEVELS[b_bits]

        palette.append(to_rgb565_swap(r, g, b))
    return palette


def main():
    if len(sys.argv) != 3:
        print("uso: python romconv_phoenix.py <rom_dir> <output_dir>")
        sys.exit(1)

    rom_dir = sys.argv[1]
    out_dir = sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)

    # ── CPU ROM 16 KB (8 × 2KB) ─────────────────────────────────────────────
    cpu_rom = bytearray(16 * 1024)
    pg_files = [
        ("ic45-pg1.1a", 0x0000),
        ("ic46-pg2.2a", 0x0800),
        ("ic47-pg3.3a", 0x1000),
        ("ic48-pg4.4a", 0x1800),
        ("ic49-pg5.5a", 0x2000),
        ("ic50-pg6.6a", 0x2800),
        ("ic51-pg7.7a", 0x3000),
        ("ic52-pg8.8a", 0x3800),
    ]
    for name, off in pg_files:
        d = read(rom_dir, name)
        if len(d) != 0x800:
            raise ValueError(f"{name} dimensione errata: {len(d)} (atteso 2048)")
        cpu_rom[off:off + 0x800] = d

    with open(os.path.join(out_dir, "phoenix_rom.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(emit_byte_array("phoenix_rom", cpu_rom,
                                "Z80 CPU ROM 16 KB (ic45..ic52)"))
    print(f"[OK] phoenix_rom.h ({len(cpu_rom)} byte)")

    # ── GFX BG 4 KB (2 plane × 2KB) ─────────────────────────────────────────
    bg_p0 = read(rom_dir, "ic23-cg1.3d")
    bg_p1 = read(rom_dir, "ic24-cg2.4d")
    bg_data = bg_p0 + bg_p1   # primo blob = plane0, secondo = plane1
    with open(os.path.join(out_dir, "phoenix_bgtiles.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(emit_byte_array("phoenix_bgtiles", bg_data,
                                "BG tiles 4 KB (256 char × 8x8 × 2bpp), plane0 + plane1"))
    print(f"[OK] phoenix_bgtiles.h ({len(bg_data)} byte)")

    # ── GFX FG 4 KB (2 plane × 2KB) ─────────────────────────────────────────
    fg_p0 = read(rom_dir, "ic39-cg3.3b")
    fg_p1 = read(rom_dir, "ic40-cg4.4b")
    fg_data = fg_p0 + fg_p1
    with open(os.path.join(out_dir, "phoenix_fgtiles.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(emit_byte_array("phoenix_fgtiles", fg_data,
                                "FG tiles 4 KB (256 char × 8x8 × 2bpp), plane0 + plane1"))
    print(f"[OK] phoenix_fgtiles.h ({len(fg_data)} byte)")

    # ── PALETTE PROM 2 × 256 byte → 256 RGB565 ──────────────────────────────
    prom_lo = read(rom_dir, "mmi6301.ic40")  # bit R0, G0, B0
    prom_hi = read(rom_dir, "mmi6301.ic41")  # bit R1, G1, B1
    if len(prom_lo) != 256 or len(prom_hi) != 256:
        raise ValueError("PROM palette dimensione non 256 byte")
    palette_rgb = decode_palette(prom_lo, prom_hi)
    with open(os.path.join(out_dir, "phoenix_palette.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(emit_word_array("phoenix_palette", palette_rgb,
                                "256 colori RGB565 byte-swapped (mmi6301 ic40 + ic41)"))
    print(f"[OK] phoenix_palette.h (256 colori)")

    # ── Dipswitches header (default coinage 1c1c, 5 lives, bonus 5K/50K) ───
    dipsw = """\
#ifndef PHOENIX_DIPSWITCHES_H
#define PHOENIX_DIPSWITCHES_H
// Default DSW0 MAME ufficiale (verificato src/mame/phoenix/phoenix.cpp):
//   bit 0,1 = lives    : 0x00 = 3 lives
//   bit 2,3 = bonus    : 0x00 = 3K/30K
//   bit 4   = coinage  : 0x00 = 1C/1C  (0x10 = 2C/1C)
//   bit 5   = unknown  : 0x20 = Off    (0x00 = On — causa drift!)
//   bit 6   = unknown  : 0x40 = Off    (0x00 = On — causa drift!)
//   bit 7   = VBLANK   : dinamico (gestito in rdZ80)
// Default ufficiale MAME = 0x60 (lives=3, bonus 3K/30K, 1C/1C, both DIPs Off).
// CRITICO: vecchio valore 0x10 metteva i 2 DIP unknown su "On", attivando
// un comportamento non documentato che causava DRIFT della nave a sinistra.
#define PHOENIX_DSW0  0x60
#endif
"""
    with open(os.path.join(out_dir, "phoenix_dipswitches.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write(dipsw)
    print("[OK] phoenix_dipswitches.h")

    print("\n[DONE] tutti i file generati in", out_dir)


if __name__ == "__main__":
    main()
