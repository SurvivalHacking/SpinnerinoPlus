"""
ROM converter for Xevious (Namco 1982) — GALAGINO FULL31
Generates header files from xevious.zip / xevios.zip ROM set (MAME format).
Output: machines/xevious/ (relative to this script)

NOTE: This generates xevious_tilemap_fg.h, xevious_cmap_fg.h etc (separate files).
      The compiled code uses xevious_tilemap.h and xevious_cmap.h (combined files)
      which were generated by an earlier converter (xevious_rom_convert.py).
      Both sets are compatible - the combined files contain the same arrays.

Hardware:
  3x Z80 @ 3.072 MHz (18.432 MHz / 6)
  Main CPU: xvi_1-4 (16KB), Sub CPU: xvi_5-6 (8KB), Sound CPU: xvi_7 (4KB)
  Video: 288x224 (portrait), 3 layers:
    BG: 8x8 2bpp tiles (512), scrolling X/Y
    Sprites: 16x16 3bpp (320), sizes 16x16/32x16/16x32/32x32
    FG: 8x8 1bpp chars (512), scrolling X/Y, transparent overlay
  Audio: Namco WSG 3 voices + 54XX discrete explosions
  Custom: 06XX bus, 50XX protection, 51XX I/O, 54XX sound

Memory map (shared by all 3 CPUs):
  $0000-$3FFF  ROM (different per CPU)
  $6800-$681F  Namco WSG sound registers
  $6820-$6827  LS259 misclatch (IRQ1, IRQ2, NMION, RESET, ...)
  $6830        Watchdog reset
  $7000-$70FF  Namco 06XX data
  $7100        Namco 06XX control
  $8000-$87FF  Work RAM + sprite SR1 (position)
  $9000-$97FF  Work RAM + sprite SR2 (flip/size)
  $A000-$A7FF  Work RAM + sprite SR3 (code/color)
  $B000-$B7FF  FG tilemap attributes
  $B800-$BFFF  BG tilemap attributes
  $C000-$C7FF  FG tilemap tile codes
  $C800-$CFFF  BG tilemap tile codes
  $D000-$D07F  Scroll/latch registers
  $F000-$FFFF  BG data ROMs (BS write address, BB read data)

MAME GFX layouts:
  FG chars: gfx_8x8x1 — 1bpp, planes={0}
  BG tiles: bgcharlayout — 2bpp 8x8, planes={0, 512*8*8}
  Sprites: spritelayout_xevious — 3bpp 16x16
    planes={RGN_FRAC(1,2)+4, 0, 4}
    xoffs={0,1,2,3, 64,65,66,67, 128,129,130,131, 192,193,194,195}
    yoffs={0,8,16,24,32,40,48,56, 256,264,272,280,288,296,304,312}
    charincrement=512 bits (64 bytes)
"""

