def write_wavetable_h(path, prom):
    """Namco WSG waveform data: 8 waveforms × 32 samples × 4-bit signed.
    Same format as Galaga wavetable.
    """
    with open(path, 'w') as f:
        f.write('// Xevious Namco WSG waveform table (8 waveforms x 32 samples)\n')
        f.write('// Auto-generated by romconv_xevious.py\n')
        f.write('const signed char xevious_wavetable[][32] = {\n')
        for w in range(8):
            samples = []
            for s in range(32):
                val = prom[w * 32 + s] & 0x0F
                # Convert 4-bit unsigned to signed (-8..+7)
                if val >= 8:
                    val -= 16
                samples.append(val)
            f.write('  { ' + ','.join(f'{v:3d}' for v in samples) + ' },\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} (8 waveforms × 32 samples)")

