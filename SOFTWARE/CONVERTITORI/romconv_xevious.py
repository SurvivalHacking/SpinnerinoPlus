def write_spritemap_h(path, variants, num_sprites):
    with open(path, 'w') as f:
        f.write(f'// Xevious sprites - 16x16, 3bpp packed (MAME spritelayout_xevious)\n')
        f.write('// 4 flip variants: [0]=normal, [1]=flipX, [2]=flipY, [3]=flipXY\n')
        f.write('// Each row: 16 pixels x 3 bits = 48 bits, stored in unsigned long long\n')
        f.write('// Pixel 0 at bits 0-2 (LSB), pixel 15 at bits 45-47\n')
        f.write(f'// {num_sprites} actual sprites + {324 - num_sprites} padding\n')
        f.write('// Auto-generated by romconv_xevious.py\n')
        f.write(f'const unsigned long long xevious_sprites[4][324][16] = {{\n')
        for vi, var in enumerate(variants):
            f.write(' {\n')
            for si, spr in enumerate(var):
                vals = []
                for (lw, rw) in spr:
                    # Combine left (pixels 0-7, 24 bits) and right (pixels 8-15, 24 bits)
                    # into one unsigned long long: right_word << 24 | left_word
                    combined = (rw << 24) | lw
                    vals.append(f'0x{combined:012x}')
                f.write('  { ' + ','.join(vals) + ' },\n')
            # Pad to 324 sprites
            for _ in range(324 - num_sprites):
                f.write('  { ' + ','.join(['0x000000000000'] * 16) + ' },\n')
            f.write(' },\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} ({num_sprites} sprites x 4 flips, padded to 324)")

def write_bg_colormap_h(path, palette, prom_lo, prom_hi):
    """BG color lookup: 128 color sets × 4 pens (2bpp).
    lookup_index = color_set * 4 + pixel_value
    palette_index = prom_lo[lookup_index] | (prom_hi[lookup_index] << 4)
    """
    with open(path, 'w') as f:
        f.write('// Xevious BG tile color map (128 sets x 4 pens, RGB565 byte-swapped)\n')
        f.write('// Auto-generated by romconv_xevious.py\n')
        f.write('const unsigned short xevious_colormap_bg[][4] = {\n')
        for c in range(128):
            colors = []
            for p in range(4):
                idx = c * 4 + p
                pal_idx = (prom_lo[idx] & 0x0F) | ((prom_hi[idx] & 0x0F) << 4)
                if pal_idx < 128:
                    r, g, b = palette[pal_idx]
                else:
                    r, g, b = 0, 0, 0  # transparent / invalid
                colors.append(rgb565_swap(r, g, b))
            f.write('  {' + ','.join(f'0x{v:04x}' for v in colors) + '},\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} (128 color sets × 4 pens)")

def write_sprite_colormap_h(path, palette, prom_lo, prom_hi):
    """Sprite color lookup: 64 color sets × 8 pens (3bpp).
    Pen that maps to palette index >= 128 (0x80) → transparent (RGB565 = 0).
    """
    with open(path, 'w') as f:
        f.write('// Xevious sprite color map (64 sets x 8 pens, RGB565 byte-swapped)\n')
        f.write('// Auto-generated by romconv_xevious.py\n')
        f.write('// Pen value 0x0000 = transparent\n')
        f.write('const unsigned short xevious_colormap_sprites[][8] = {\n')
        for c in range(64):
            colors = []
            for p in range(8):
                idx = c * 8 + p
                pal_idx = (prom_lo[idx] & 0x0F) | ((prom_hi[idx] & 0x0F) << 4)
                if pal_idx < 128:
                    r, g, b = palette[pal_idx]
                    colors.append(rgb565_swap(r, g, b))
                else:
                    colors.append(0x0000)  # transparent
            f.write('  {' + ','.join(f'0x{v:04x}' for v in colors) + '},\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} (64 color sets × 8 pens)")

def write_fg_colormap_h(path, palette):
    """FG char color lookup: 64 color sets × 2 pens (1bpp).
    pen 0 = transparent (0x0000), pen 1 = palette[color_code].
    Only store pen 1 since pen 0 is always transparent.
    """
    with open(path, 'w') as f:
        f.write('// Xevious FG char color map (64 color sets, RGB565 byte-swapped)\n')
        f.write('// Auto-generated by romconv_xevious.py\n')
        f.write('// fg_cmap[color] = pen 1 color (pen 0 = transparent, skip)\n')
        f.write('const unsigned short xevious_colormap_fg[] = {\n')
        for c in range(64):
            pal_idx = c  # FG: direct palette mapping
            if pal_idx < 128:
                r, g, b = palette[pal_idx]
                val = rgb565_swap(r, g, b)
            else:
                val = 0x0000
            f.write(f'  0x{val:04x},\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} (64 color sets)")

