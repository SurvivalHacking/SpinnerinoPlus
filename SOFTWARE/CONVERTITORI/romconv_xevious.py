def load(z, name, expected=None):
    names_lc = {n.lower(): n for n in z.namelist()}
    # Try: original name, case-insensitive, xevios alias, alias case-insensitive
    alias = XEVIOS_ALIASES.get(name, None)
    candidates = [name, names_lc.get(name.lower(), None), alias, names_lc.get(alias.lower(), None) if alias else None]
    for try_n in candidates:
        if try_n is None: continue
        try:
            d = z.read(try_n)
            if expected and len(d) != expected:
                print(f"  WARN: {try_n} is {len(d)}B, expected {expected}")
            print(f"  {try_n}: {len(d)}B")
            return d
        except KeyError:
            continue
    print(f"  ERROR: {name} not found (also tried {alias})!")
    sys.exit(1)

def read_bit(data, pos):
    return (data[pos >> 3] >> (7 - (pos & 7))) & 1

def rgb565_swap(r, g, b):
    """Convert RGB888 to RGB565 byte-swapped (for ESP32 SPI display)."""
    c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return ((c >> 8) & 0xFF) | ((c & 0xFF) << 8)

# ── Palette decode (Xevious resistor network: 4 bits per gun) ──
def decode_palette(prom_r, prom_g, prom_b):
    """Decode 128 palette entries from 3 color PROMs.
    Resistor weights: 220, 470, 1K, 2.2K ohm → 0x0e, 0x1f, 0x43, 0x8f per bit.
    """
    palette = []
    for i in range(128):
        rv = prom_r[i] & 0x0F
        gv = prom_g[i] & 0x0F
        bv = prom_b[i] & 0x0F
        r = 0x0e * (rv & 1) + 0x1f * ((rv >> 1) & 1) + 0x43 * ((rv >> 2) & 1) + 0x8f * ((rv >> 3) & 1)
        g = 0x0e * (gv & 1) + 0x1f * ((gv >> 1) & 1) + 0x43 * ((gv >> 2) & 1) + 0x8f * ((gv >> 3) & 1)
        b = 0x0e * (bv & 1) + 0x1f * ((bv >> 1) & 1) + 0x43 * ((bv >> 2) & 1) + 0x8f * ((bv >> 3) & 1)
        palette.append((r, g, b))
    return palette

# ── BG tile decode: 8x8 2bpp ──
def decode_bg_tiles(gfx2):
    """512 BG tiles, 8x8 2bpp. Same format as Galaga tiles.
    planes = {0, 512*8*8} = {0, 32768 bits}
    Plane 0 from first 4KB (xvi_13), plane 1 from second 4KB (xvi_14).
    Returns list of 512 tiles, each = list of 8 unsigned short (8 pixels × 2bpp packed).
    """
    plane_off = [0, 512 * 8 * 8]  # bit offsets for plane 0, plane 1
    tiles = []
    for t in range(512):
        base = t * 64  # charincrement = 8*8 = 64 bits
        rows = []
        for y in range(8):
            packed = 0
            for x in range(8):
                bit_pos = base + y * 8 + x
                b0 = read_bit(gfx2, bit_pos + plane_off[0])  # plane 0
                b1 = read_bit(gfx2, bit_pos + plane_off[1])  # plane 1
                pixel = (b1 << 1) | b0  # plane 1 = MSB
                packed |= (pixel << (x * 2))
            rows.append(packed)
        tiles.append(rows)
    return tiles

# ── FG char decode: 8x8 1bpp ──
def decode_fg_chars(gfx1):
    """512 FG characters, 8x8 1bpp.
    Each byte = 8 pixels of one row (bit 7 = leftmost pixel).
    Returns raw bytes (4KB) — stored as-is for compact flash usage.
    """
    # gfx_8x8x1 layout: planes={0}, xoffs={0,1,2,3,4,5,6,7}, yoffs={0..7}*8
    # Simply return the raw ROM data
    return bytes(gfx1[:4096])

# ── Sprite decode: 16x16 3bpp (MAME spritelayout_xevious) ──
def decode_sprites(gfx3, num_sprites):
    """Decode sprites from prepared gfx3 region.
    planes = {RGN_FRAC(1,2)+4, 0, 4}
    xoffs = {0,1,2,3, 64,65,66,67, 128,129,130,131, 192,193,194,195}
    yoffs = {0,8,16,24,32,40,48,56, 256,264,272,280,288,296,304,312}
    charincrement = 512 bits = 64 bytes

    Returns list of sprites, each = list of 16 rows,
    each row = (left_word, right_word) with 8 pixels × 3bpp in unsigned long.
    """
    region_size = len(gfx3)
    half = region_size // 2  # RGN_FRAC(1,2) in bytes
    half_bits = half * 8     # RGN_FRAC(1,2) in bits

    # Plane bit offsets (MAME order: MSB first)
    # planes[0] = bit 2 (MSB) = RGN_FRAC(1,2)*8 + 4
    # planes[1] = bit 1       = 0
    # planes[2] = bit 0 (LSB) = 4
    plane_off = [half_bits + 4, 0, 4]

    xoffs = [0, 1, 2, 3, 64, 65, 66, 67, 128, 129, 130, 131, 192, 193, 194, 195]
    yoffs = [0, 8, 16, 24, 32, 40, 48, 56, 256, 264, 272, 280, 288, 296, 304, 312]
    step = 512  # charincrement in bits

    sprites = []
    for s in range(num_sprites):
        base = s * step
        rows = []
        for y in range(16):
            left_word = 0   # pixels 0-7
            right_word = 0  # pixels 8-15
            for x in range(16):
                pixel = 0
                bp = base + yoffs[y] + xoffs[x]
                for p in range(3):
                    bit_abs = bp + plane_off[p]
                    byte_idx = bit_abs >> 3
                    bit_idx = bit_abs & 7
                    if byte_idx < region_size and (gfx3[byte_idx] >> (7 - bit_idx)) & 1:
                        pixel |= (1 << (2 - p))  # planes[0]=MSB=bit2, planes[2]=LSB=bit0
                if x < 8:
                    left_word |= (pixel << (x * 3))
                else:
                    right_word |= (pixel << ((x - 8) * 3))
            rows.append((left_word, right_word))
        sprites.append(rows)
    return sprites

def get_pixel(spr_row, x):
    """Extract 3bpp pixel from packed row tuple (left_word, right_word)."""
    lw, rw = spr_row
    if x < 8:
        return (lw >> (x * 3)) & 7
    else:
        return (rw >> ((x - 8) * 3)) & 7

def pack_row(pixels):
    """Pack 16 pixels (3bpp) into (left_word, right_word) tuple."""
    lw = 0
    rw = 0
    for x in range(8):
        lw |= (pixels[x] << (x * 3))
    for x in range(8, 16):
        rw |= (pixels[x] << ((x - 8) * 3))
    return (lw, rw)

def prerotate_sprite_rot90cw(native):
    """Pre-rotate sprite for ROT90CW display.
    prerotated[r][c] = native[15-c][r]
    This makes the renderer draw correctly on a portrait display.
    """
    prerot = []
    for r in range(16):
        pixels = []
        for c in range(16):
            pixels.append(get_pixel(native[15 - c], r))
        prerot.append(pack_row(pixels))
    return prerot

def make_flipped_sprites(sprites):
    """Pre-rotate sprites for ROT90CW display, then generate 4 flip variants."""
    # Pre-rotate all sprites first
    rotated = [prerotate_sprite_rot90cw(spr) for spr in sprites]

    def reverse_word(w):
        out = 0
        for i in range(8):
            px = (w >> (i * 3)) & 7
            out |= (px << ((7 - i) * 3))
        return out

    all_variants = [[], [], [], []]
    for spr in rotated:
        all_variants[0].append(spr)
        fx = [(reverse_word(rw), reverse_word(lw)) for (lw, rw) in spr]
        all_variants[1].append(fx)
        all_variants[2].append(list(reversed(spr)))
        fxy = [(reverse_word(rw), reverse_word(lw)) for (lw, rw) in reversed(spr)]
        all_variants[3].append(fxy)
    return all_variants

