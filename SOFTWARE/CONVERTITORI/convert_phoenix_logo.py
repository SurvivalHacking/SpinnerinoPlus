#!/usr/bin/env python3
# convert_phoenix_logo.py
# Converte un'immagine logo Phoenix (es. flyer JPEG) nel formato RAW 224x96
# RGB565 byte-swapped usato dal BootMenu di SPINNERINO.
#
# Uso:
#   python convert_phoenix_logo.py <input.jpg> <output.h>
#
# Esempio:
#   python convert_phoenix_logo.py phoenix.jpeg machines/phoenix/phoenix_logo.h

import sys
import os
from PIL import Image

LOGO_W = 224
LOGO_H = 96


def to_rgb565_swap(r, g, b):
    rgb565 = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    return ((rgb565 >> 8) | (rgb565 << 8)) & 0xFFFF


def main():
    if len(sys.argv) != 3:
        print("uso: python convert_phoenix_logo.py <input.jpg> <output.h>")
        sys.exit(1)

    in_path = sys.argv[1]
    out_path = sys.argv[2]
    if not os.path.isfile(in_path):
        print(f"ERRORE: input non trovato: {in_path}")
        sys.exit(2)

    img = Image.open(in_path).convert("RGB")
    img = img.resize((LOGO_W, LOGO_H), Image.LANCZOS)
    px = img.load()

    pixels = []
    for y in range(LOGO_H):
        for x in range(LOGO_W):
            r, g, b = px[x, y]
            pixels.append(to_rgb565_swap(r, g, b))

    var = "phoenix"
    upper = var.upper()
    lines = [
        "// Auto-generated by convert_phoenix_logo.py",
        f"// {LOGO_W}x{LOGO_H} RGB565 byte-swap (ESP32 SPI BE), RAW format",
        f"#define {upper}_LOGO_W {LOGO_W}",
        f"#define {upper}_LOGO_H {LOGO_H}",
        f"const unsigned short {var}_logo[{LOGO_W}*{LOGO_H}] PROGMEM = {{",
    ]
    per_line = 12
    total = LOGO_W * LOGO_H
    for r in range(0, total, per_line):
        chunk = pixels[r:r + per_line]
        sep = "," if r + per_line < total else ""
        lines.append("  " + ", ".join(f"0x{p:04X}" for p in chunk) + sep)
    lines.append("};")
    lines.append("")

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"[OK] scritto {out_path} ({os.path.getsize(out_path)} byte)")


if __name__ == "__main__":
    main()
