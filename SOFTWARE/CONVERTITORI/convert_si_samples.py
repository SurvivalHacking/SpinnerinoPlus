"""
Convert Space Invaders WAV samples to C header arrays for playback at 24kHz.
Resamples to 24kHz, converts to signed 8-bit PCM, outputs as PROGMEM arrays.
"""
import os
import sys
import wave
import struct

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(SCRIPT_DIR)
PARENT_DIR = os.path.dirname(PROJECT_DIR)
SOUNDS_DIR = os.path.join(PARENT_DIR, "si_sounds")
OUTPUT_PATH = os.path.join(PROJECT_DIR, "machines", "spaceinvaders", "spaceinvaders_samples.h")

TARGET_RATE = 12000  # half rate to save flash space (playback at 24kHz = 2x each sample)

def read_wav(path):
    """Read WAV file, return (samples_as_floats, sample_rate)"""
    with wave.open(path, 'rb') as w:
        nch = w.getnchannels()
        sw = w.getsampwidth()
        rate = w.getframerate()
        nframes = w.getnframes()
        raw = w.readframes(nframes)

    if sw == 1:
        # 8-bit unsigned
        samples = [(b - 128) / 128.0 for b in raw]
    elif sw == 2:
        # 16-bit signed
        vals = struct.unpack(f'<{nframes * nch}h', raw)
        samples = [v / 32768.0 for v in vals]
    else:
        print(f"  Unsupported sample width: {sw}")
        sys.exit(1)

    # Mix to mono if stereo
    if nch == 2:
        mono = []
        for i in range(0, len(samples), 2):
            mono.append((samples[i] + samples[i+1]) / 2.0)
        samples = mono

    return samples, rate

def resample(samples, src_rate, dst_rate):
    """Simple linear interpolation resample"""
    ratio = src_rate / dst_rate
    out_len = int(len(samples) / ratio)
    result = []
    for i in range(out_len):
        src_pos = i * ratio
        idx = int(src_pos)
        frac = src_pos - idx
        if idx + 1 < len(samples):
            val = samples[idx] * (1 - frac) + samples[idx + 1] * frac
        else:
            val = samples[idx] if idx < len(samples) else 0
        result.append(val)
    return result

def to_signed8(samples):
    """Convert float samples (-1..1) to signed 8-bit (-127..127)"""
    result = []
    # Normalize to peak
    peak = max(abs(s) for s in samples) if samples else 1.0
    if peak < 0.01:
        peak = 1.0
    for s in samples:
        val = int(s / peak * 127)
        if val > 127: val = 127
        if val < -127: val = -127
        result.append(val)
    return result

def write_header(arrays, output_path):
    """Write C header with PROGMEM arrays"""
    with open(output_path, 'w') as f:
        f.write("// Space Invaders audio samples - 24kHz signed 8-bit PCM\n")
        f.write("// Auto-generated by convert_si_samples.py - DO NOT EDIT\n\n")
        f.write("#include <pgmspace.h>\n\n")

        for name, data in arrays:
            f.write(f"#define {name}_LEN {len(data)}\n")
            f.write(f"const signed char {name}[] PROGMEM = {{\n")
            for i in range(0, len(data), 32):
                chunk = data[i:i+32]
                line = ", ".join(str(v) for v in chunk)
                if i + 32 < len(data):
                    line += ","
                f.write(f"  {line}\n")
            f.write(f"}};\n\n")

    print(f"Written: {output_path}")

def process_wav(name, filename, max_seconds=None):
    path = os.path.join(SOUNDS_DIR, filename)
    if not os.path.exists(path):
        print(f"  WARNING: {path} not found")
        return None

    print(f"Processing {filename}...")
    samples, rate = read_wav(path)
    print(f"  Source: {len(samples)} samples @ {rate}Hz ({len(samples)/rate:.2f}s)")

    # Trim to max duration
    if max_seconds and len(samples) > int(rate * max_seconds):
        samples = samples[:int(rate * max_seconds)]
        print(f"  Trimmed to {len(samples)/rate:.2f}s")

    if rate != TARGET_RATE:
        samples = resample(samples, rate, TARGET_RATE)
        print(f"  Resampled to {len(samples)} samples @ {TARGET_RATE}Hz ({len(samples)/TARGET_RATE:.2f}s)")

    data = to_signed8(samples)
    print(f"  Output: {len(data)} bytes")
    return (name, data)

def main():
    arrays = []

    result = process_wav("si_sample_shot", "Shot.wav", max_seconds=0.20)
    if result: arrays.append(result)

    result = process_wav("si_sample_invhit", "InvHit.wav", max_seconds=0.25)
    if result: arrays.append(result)

    if arrays:
        write_header(arrays, OUTPUT_PATH)
        total = sum(len(d) for _, d in arrays)
        print(f"\nTotal: {total} bytes of sample data")

if __name__ == "__main__":
    main()
