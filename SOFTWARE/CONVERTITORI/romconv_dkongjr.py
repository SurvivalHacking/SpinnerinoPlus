#!/usr/bin/env python3
"""
ROM converter for Donkey Kong Jr (Nintendo 1982, set "dkongjrj") — GALAGINO arcade emulator
Generates header files from dkongjrj.zip ROM set (MAME format).

Hardware:
  Main CPU: Z80 @ 3.072MHz
  Sound CPU: MB8884 (i8048/49 compatible)
  Video: 256x224 ROT270 (portrait), 8x8 2bpp tiles (512), 16x16 2bpp sprites (128)
  Palette: 256 entries from 2x 4-bit PROMs + 256-byte colormap PROM
  Bank-switched palette (2 banks bit0+bit1 -> 4 effective) and tile gfx bank

Memory map (Z80):
  0x0000-0x5FFF  ROM (24K) — c_5ba/c_5ca/c_5ea con ROM_CONTINUE multipli
  0x6000-0x6FFF  RAM (4K)
  0x7000-0x77FF  Sprite/Video RAM
  0x7C00         IN0 (joystick)
  0x7C80         IN1 / gfx_bank
  0x7D00-0x7D07  audio triggers (climb/jump/land/roar/T0/T1/snapjaw/walk)
  0x7D80         DSW / NMI enable / DMA / palette_bank

ROM names in dkongjrj.zip:
  c_5ba.bin, c_5ca.bin, c_5ea.bin   -> CPU ROM (8K each)
  c_3h.bin                          -> Sound CPU ROM (4K)
  v_3na.bin, v_3pa.bin              -> Tile GFX (4K each, 2 bitplanes)
  v_7c.bin, v_7d.bin, v_7e.bin, v_7f.bin -> Sprite GFX (2K each, 4 bitplanes)
  c-2e.bpr, c-2f.bpr                -> Palette PROM (256B each, 4-bit nibble)
  v-2n.bpr                          -> Colormap lookup PROM (256B)
"""

import sys, os, zipfile

ZIP_CANDIDATES = ('dkongjrj.zip',)

SEARCH = [
    os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'romszip'),
    os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'),
    os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'),
    os.path.expanduser('~/Desktop'),
    os.path.expanduser('~/Desktop/PROGETTI SH'),
    '.',
]

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'machines', 'dkongjr')


def find_zip():
    for d in SEARCH:
        for name in ZIP_CANDIDATES:
            p = os.path.join(d, name)
            if os.path.exists(p):
                return p
    if len(sys.argv) > 1 and os.path.exists(sys.argv[1]):
        return sys.argv[1]
    return None


def load(z, name, expected=None):
    names_lc = {n.lower(): n for n in z.namelist()}
    target = names_lc.get(name.lower(), name)
    try:
        d = z.read(target)
    except KeyError:
        print(f"  ERROR: {name} not found in zip")
        sys.exit(1)
    if expected and len(d) != expected:
        print(f"  WARN: {name} is {len(d)}B, expected {expected}")
    print(f"  {name}: {len(d)}B")
    return d


# ── CPU ROM (rom1) — 24K mapped with ROM_CONTINUE ──
def build_cpu_rom(z):
    rom_5b = load(z, "c_5ba.bin", 0x2000)
    rom_5c = load(z, "c_5ca.bin", 0x2000)
    rom_5e = load(z, "c_5ea.bin", 0x2000)

    mem = bytearray([0xFF] * 0x10000)

    # c_5ba.bin: LOAD 0x0000+0x1000, CONTINUE 0x3000+0x1000
    mem[0x0000:0x1000] = rom_5b[0x0000:0x1000]
    mem[0x3000:0x4000] = rom_5b[0x1000:0x2000]

    # c_5ca.bin: LOAD 0x2000+0x0800, CONTINUE 0x4800+0x0800, 0x1000+0x0800, 0x5800+0x0800
    mem[0x2000:0x2800] = rom_5c[0x0000:0x0800]
    mem[0x4800:0x5000] = rom_5c[0x0800:0x1000]
    mem[0x1000:0x1800] = rom_5c[0x1000:0x1800]
    mem[0x5800:0x6000] = rom_5c[0x1800:0x2000]

    # c_5ea.bin: LOAD 0x4000+0x0800, CONTINUE 0x2800+0x0800, 0x5000+0x0800, 0x1800+0x0800
    mem[0x4000:0x4800] = rom_5e[0x0000:0x0800]
    mem[0x2800:0x3000] = rom_5e[0x0800:0x1000]
    mem[0x5000:0x5800] = rom_5e[0x1000:0x1800]
    mem[0x1800:0x2000] = rom_5e[0x1800:0x2000]

    return bytes(mem[:0x6000])


def write_blob_h(path, name, data, header_comment):
    with open(path, 'w') as f:
        f.write(f'// {header_comment}\n')
        f.write(f'// Auto-generated by romconv_dkongjr.py\n')
        f.write(f'const unsigned char {name}[{len(data)}] = {{\n')
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            f.write('  ' + ','.join(f'0x{b:02x}' for b in chunk) + ',\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} ({len(data)} bytes)")


# ── Tile GFX: 512 tiles, 8x8 2bpp ──
def decode_tile(d0, d1):
    """Decode one 8x8 tile from two 8-byte bitplane chunks."""
    char = []
    for y in range(8):
        row = []
        for x in range(8):
            c0 = 1 if d0[7 - x] & (0x80 >> y) else 0
            c1 = 2 if d1[7 - x] & (0x80 >> y) else 0
            row.append(c0 + c1)
        char.append(row)
    return char


def pack_tile_row(row):
    """Pack 8 pixels (2bpp) into one 16-bit short, LSB-first like dkong."""
    val = 0
    for x in range(8):
        val = (val >> 2) | (row[x] << 14)
    return val & 0xFFFF


def build_tiles(z):
    p0 = load(z, "v_3na.bin", 0x1000)
    p1 = load(z, "v_3pa.bin", 0x1000)
    tiles = []
    for i in range(512):
        d0 = p0[8 * i:8 * (i + 1)]
        d1 = p1[8 * i:8 * (i + 1)]
        tile = decode_tile(d0, d1)
        tiles.append([pack_tile_row(r) for r in tile])
    return tiles


def write_tilemap_h(path, tiles):
    with open(path, 'w') as f:
        f.write('// Donkey Kong Jr tiles 8x8 2bpp (512 tiles)\n')
        f.write('// Auto-generated by romconv_dkongjr.py\n')
        f.write(f'const unsigned short dkongjr_tilemap[{len(tiles)}][8] = {{\n')
        for t in tiles:
            f.write('  { ' + ','.join(f'0x{v:04x}' for v in t) + ' },\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} ({len(tiles)} tiles)")


# ── Sprite GFX: 128 sprites, 16x16 2bpp, 4 flip variants ──
def decode_sprite(chunks):
    """Decode one 16x16 sprite from 4 chunks of 16 bytes each (2 bitplanes)."""
    sprite = []
    for y in range(16):
        row = []
        for x in range(16):
            c0 = 1 if chunks[y // 8][15 - x] & (0x80 >> (y & 7)) else 0
            c1 = 2 if chunks[y // 8 + 2][15 - x] & (0x80 >> (y & 7)) else 0
            row.append(c0 + c1)
        sprite.append(row)
    return sprite


def dump_sprite(sprite, flip_x, flip_y):
    """Pack a 16x16 sprite into 16 unsigned long (32-bit), 2 bits per pixel."""
    rows = []
    yr = reversed(range(16)) if flip_y else range(16)
    for y in yr:
        val = 0
        xr = reversed(range(16)) if flip_x else range(16)
        for x in xr:
            val = (val << 2) | sprite[y][x]
        rows.append(val & 0xFFFFFFFF)
    return rows


def build_sprites(z):
    files = ["v_7c.bin", "v_7d.bin", "v_7e.bin", "v_7f.bin"]
    data = [load(z, n, 0x800) for n in files]
    sprites = []
    for i in range(128):
        chunks = [d[16 * i:16 * (i + 1)] for d in data]
        sprites.append(decode_sprite(chunks))
    return sprites


def write_spritemap_h(path, sprites):
    with open(path, 'w') as f:
        f.write('// Donkey Kong Jr sprites 16x16 2bpp (128 sprites, 4 flip variants)\n')
        f.write('// Auto-generated by romconv_dkongjr.py\n')
        f.write(f'const unsigned long dkongjr_sprites[4][{len(sprites)}][16] = {{\n')
        for (fx, fy, label) in [(False, False, 'No'), (False, True, 'Y'),
                                 (True, False, 'X'), (True, True, 'XY')]:
            f.write(f'  // Flip: {label}\n  {{\n')
            for s in sprites:
                rows = dump_sprite(s, fx, fy)
                f.write('    { ' + ','.join(f'0x{r:08x}' for r in rows) + ' },\n')
            f.write('  },\n')
        f.write('};\n')
    print(f"  -> {os.path.basename(path)} ({len(sprites)} sprites x 4 flips)")


# ── Palette + Colormap ──
def get_bit(value, bit):
    return (value >> bit) & 1


def build_palette(z):
    prom_lo = load(z, "c-2e.bpr", 0x100)
    prom_hi = load(z, "c-2f.bpr", 0x100)
    pal = []
    for i in range(256):
        lo = prom_lo[i]
        hi = prom_hi[i]
        # MAME dkong_decode_info bit mapping
        r3 = (get_bit(hi, 3) << 2) | (get_bit(hi, 2) << 1) | (get_bit(hi, 1) << 0)
        g3 = (get_bit(hi, 0) << 2) | (get_bit(lo, 3) << 1) | (get_bit(lo, 2) << 0)
        b2 = (get_bit(lo, 1) << 1) | (get_bit(lo, 0) << 0)
        # Inverted linear scale (hardware inverts the signals)
        r5 = 31 - (31 * r3 // 7)
        g6 = 63 - (63 * g3 // 7)
        b5 = 31 - (31 * b2 // 3)
        rgb = (r5 << 11) | (g6 << 5) | b5
        # Byte swap for display SPI
        pal.append(((rgb & 0xFF00) >> 8) | ((rgb & 0x00FF) << 8))
    return pal


def write_cmap_h(path, z, palette):
    lookup = load(z, "v-2n.bpr", 0x100)

    with open(path, 'w') as f:
        f.write('// Donkey Kong Jr colormap (RGB565 byte-swapped)\n')
        f.write('// Palette: c-2e.bpr + c-2f.bpr, lookup: v-2n.bpr (4 palette banks)\n')
        f.write('// Auto-generated by romconv_dkongjr.py\n\n')

        # Tile colormap: [4][256][4]
        f.write('const unsigned short dkongjr_colormap[][256][4] = {\n')
        banks = []
        for s in range(4):
            entries = []
            for idx in lookup:
                off = idx + 16 * s
                cols = [palette[4 * off + p] for p in range(4)]
                entries.append('{' + ','.join(f'0x{c:04x}' for c in cols) + '}')
            banks.append('  {\n    ' + ',\n    '.join(entries) + '\n  }')
        f.write(',\n'.join(banks))
        f.write('\n};\n\n')

        # Sprite colormap: [4][16][4]
        f.write('const unsigned short dkongjr_colormap_sprite[][16][4] = {\n')
        banks = []
        for s in range(4):
            entries = []
            for i in range(16):
                off = i + 16 * s
                cols = [palette[4 * off + p] for p in range(4)]
                entries.append('{' + ','.join(f'0x{c:04x}' for c in cols) + '}')
            banks.append('  {\n    ' + ',\n    '.join(entries) + '\n  }')
        f.write(',\n'.join(banks))
        f.write('\n};\n')
    print(f"  -> {os.path.basename(path)} (tile 4x256x4 + sprite 4x16x4)")


# ── Main ──
def main():
    zip_path = find_zip()
    if not zip_path:
        print("ERROR: dkongjrj.zip not found.")
        print("Tried these locations:")
        for d in SEARCH:
            print(f"  - {os.path.abspath(d)}")
        print("Usage: python romconv_dkongjr.py [path/to/dkongjrj.zip]")
        sys.exit(1)

    print(f"Using ROM zip: {zip_path}")
    os.makedirs(OUT_DIR, exist_ok=True)

    with zipfile.ZipFile(zip_path) as z:
        print("\n[1/5] CPU ROM (24K with ROM_CONTINUE)...")
        cpu = build_cpu_rom(z)
        write_blob_h(os.path.join(OUT_DIR, 'dkongjr_rom1.h'),
                     'dkongjr_rom1', cpu,
                     'Donkey Kong Jr main CPU ROM (24K, ROM_LOAD+ROM_CONTINUE)')

        print("\n[2/5] Sound CPU ROM (4K)...")
        snd = load(z, "c_3h.bin", 0x1000)
        write_blob_h(os.path.join(OUT_DIR, 'dkongjr_rom2.h'),
                     'dkongjr_rom2', snd,
                     'Donkey Kong Jr sound CPU ROM (MB8884 / i8048)')

        print("\n[3/5] Tile GFX (512 tiles)...")
        tiles = build_tiles(z)
        write_tilemap_h(os.path.join(OUT_DIR, 'dkongjr_tilemap.h'), tiles)

        print("\n[4/5] Sprite GFX (128 sprites)...")
        sprites = build_sprites(z)
        write_spritemap_h(os.path.join(OUT_DIR, 'dkongjr_spritemap.h'), sprites)

        print("\n[5/5] Palette + colormap...")
        palette = build_palette(z)
        write_cmap_h(os.path.join(OUT_DIR, 'dkongjr_cmap.h'), z, palette)

    print("\nDone. All 5 header files generated in:")
    print(f"  {OUT_DIR}")
    print("\nNext: enable ENABLE_DKONGJR in config.h, then compile.")


if __name__ == '__main__':
    main()
