#!/usr/bin/env python3
# ============================================================================
# SPINNERINO P4 - convert_splash.py
# Converte un'immagine in array RGB565 byte-swapped per ST7789 portrait 240x320
# Genera splash_logo.h da includere nel progetto.
#
# Uso: python convert_splash.py [src_image] [dst_header]
# ============================================================================
import sys, os
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else 'spinnerino_splash.jpg'
DST = sys.argv[2] if len(sys.argv) > 2 else 'splash_logo.h'
# LANDSCAPE 320x232 pre-ruotato 90 antiorario (sorgente Arkanoid SH style):
# il display lavora in MAC=0x60 landscape (FB 320x232) ma e' fisicamente portrait,
# quindi pre-ruotiamo l'immagine portrait per farla apparire dritta all'utente.
W = 320
H = 232

img = Image.open(SRC).convert('RGB')

# Step 1: crop+resize a portrait H x W (= 232 x 320, ratio 232/320 ≈ 0.725)
PORTRAIT_W = H   # 232
PORTRAIT_H = W   # 320
src_w, src_h = img.size
src_ratio = src_w / src_h
dst_ratio = PORTRAIT_W / PORTRAIT_H
if src_ratio > dst_ratio:
    new_w = int(src_h * dst_ratio)
    off_x = (src_w - new_w) // 2
    img = img.crop((off_x, 0, off_x + new_w, src_h))
else:
    new_h = int(src_w / dst_ratio)
    off_y = (src_h - new_h) // 2
    img = img.crop((0, off_y, src_w, off_y + new_h))
img = img.resize((PORTRAIT_W, PORTRAIT_H), Image.LANCZOS)

# Step 2: ruota 90 antiorario per ottenere landscape pre-ruotato
img = img.rotate(90, expand=True)
# Ora img.size = (W, H) = (320, 232)

with open(DST, 'w') as f:
    f.write('// Auto-generated by convert_splash.py - DO NOT EDIT\n')
    f.write('// Source: %s\n' % os.path.basename(SRC))
    f.write('// Format: RGB565 byte-swapped (big-endian) for ST7789 SPI\n')
    f.write('#ifndef _SPLASH_LOGO_H_\n#define _SPLASH_LOGO_H_\n\n')
    f.write('#define SPLASH_W %d\n' % W)
    f.write('#define SPLASH_H %d\n\n' % H)
    f.write('const unsigned short splash_logo[%d] = {\n' % (W * H))
    pixels = img.load()
    cnt = 0
    for y in range(H):
        for x in range(W):
            r, g, b = pixels[x, y]
            r5 = (r >> 3) & 0x1F
            g6 = (g >> 2) & 0x3F
            b5 = (b >> 3) & 0x1F
            rgb = (r5 << 11) | (g6 << 5) | b5
            # Byte-swap per ST7789: hi-byte first sul SPI
            sw = ((rgb & 0xFF) << 8) | ((rgb >> 8) & 0xFF)
            if cnt % 12 == 0:
                f.write('  ')
            f.write('0x%04X,' % sw)
            cnt += 1
            if cnt % 12 == 0:
                f.write('\n')
            else:
                f.write(' ')
    if cnt % 12 != 0:
        f.write('\n')
    f.write('};\n\n#endif\n')

size_kb = (W * H * 2) / 1024.0
print('OK: %dx%d pixels, %d entries, ~%.1f KB Flash' % (W, H, cnt, size_kb))
print('Output: %s' % DST)
