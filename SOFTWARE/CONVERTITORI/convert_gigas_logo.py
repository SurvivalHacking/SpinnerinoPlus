#!/usr/bin/env python3
"""
convert_gigas_logo.py — converte il logo Gigas in header RGB565 RAW per il
menu di SPINNERINO (ESP32-S3 Zero Mini + ST7789 320x240).

Output: 224x96 RGB565 byte-swap, formato RAW per scroll fluido nel carousel.

Sorgente: LOGHI/Gigas.jpeg (RGB 373x135)
Output:   arkanoid/machines/gigas/gigas_logo.h   const gigas_logo[224*96]
"""
from PIL import Image
import os

LOGO_W, LOGO_H = 224, 96
SRC = r"C:\Users\Tecnico\Desktop\PROGETTI SH\SPINNERINO\SPINNERINO NEW P4p\LOGHI\Gigas.jpeg"
OUT = r"C:\Users\Tecnico\Desktop\PROGETTI SH\SPINNERINO\SPINNERINO NEW P4p\SPINNERINO\machines\gigas\gigas_logo.h"

def rgb888_to_rgb565_swapped(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    rgb565 = (r5 << 11) | (g6 << 5) | b5
    return ((rgb565 >> 8) & 0xFF) | ((rgb565 & 0xFF) << 8)

def fit_into(img, target_w, target_h, scale=0.80):
    """Contain + scale: ridimensiona il logo al 'scale' del canvas (default 80%)
    mantenendo l'aspect ratio, poi centra con padding nero attorno.
    """
    inner_w = int(target_w * scale)
    inner_h = int(target_h * scale)
    w, h = img.size
    aspect = w / h
    inner_aspect = inner_w / inner_h
    if aspect > inner_aspect:
        new_w = inner_w
        new_h = int(inner_w / aspect)
    else:
        new_h = inner_h
        new_w = int(inner_h * aspect)
    resized = img.resize((new_w, new_h), Image.LANCZOS)
    canvas = Image.new('RGB', (target_w, target_h), (0, 0, 0))
    pos = ((target_w - new_w) // 2, (target_h - new_h) // 2)
    if resized.mode == 'RGBA':
        canvas.paste(resized, pos, resized)
    else:
        canvas.paste(resized, pos)
    return canvas

def write_header(path, var_name, pixels):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write("// Auto-generated by convert_gigas_logo.py\n")
        f.write(f"// {LOGO_W}x{LOGO_H} RGB565 byte-swap (ESP32 SPI BE), RAW format\n")
        f.write(f"#define {var_name.upper()}_W {LOGO_W}\n")
        f.write(f"#define {var_name.upper()}_H {LOGO_H}\n")
        f.write(f"const unsigned short {var_name}[{LOGO_W}*{LOGO_H}] PROGMEM = {{\n")
        for i in range(0, len(pixels), 12):
            chunk = pixels[i:i+12]
            f.write("  " + ", ".join(f"0x{p:04X}" for p in chunk) + ",\n")
        f.write("};\n")
    print(f"  wrote {path}  ({len(pixels)} px = {len(pixels)*2} bytes)")

def main():
    print(f"[gigas_logo] {SRC}")
    img = Image.open(SRC)
    print(f"  source: {img.size} mode={img.mode}")
    if img.mode not in ('RGB', 'RGBA'):
        img = img.convert('RGB')
    canvas = fit_into(img, LOGO_W, LOGO_H)
    pixels = [rgb888_to_rgb565_swapped(r, g, b) for (r, g, b) in canvas.getdata()]
    write_header(OUT, "gigas_logo", pixels)
    print("Done!")

if __name__ == '__main__':
    main()
