#!/usr/bin/env python3
"""
convert_arcade_logos.py — converte i loghi arcade in header RGB565 RAW
per il menu di ARKANOID SH (ESP32-S3 Zero Mini + ST7789 320x240).

Output: 224x96 RGB565 byte-swap (formato standard Galagino), formato RAW
(NO RLE) per permettere scroll fluido pixel-per-pixel nel menu carousel.

Sorgenti:
  C:\\Users\\Tecnico\\Desktop\\ARKANOID SH\\LOGHI\\arkanoid logo.jpeg
  C:\\Users\\Tecnico\\Desktop\\ARKANOID SH\\LOGHI\\tempest logo.jpeg

Output:
  arkanoid/machines/arkanoid/arkanoid_logo.h   const arkanoid_logo[224*96]
  arkanoid/machines/tempest/tempest_logo.h     const tempest_logo[224*96]
"""
from PIL import Image
import os

LOGO_W, LOGO_H = 224, 96
LOGOS_DIR = r"C:\Users\Tecnico\Desktop\PROGETTI SH\SPINNERINO\SPINNERINO NEW P4p\LOGHI"
OUT_BASE  = r"C:\Users\Tecnico\Desktop\PROGETTI SH\SPINNERINO\SPINNERINO NEW P4p\SPINNERINO\machines"

LOGOS = [
    ("arkanoid logo.jpeg", "arkanoid", "arkanoid_logo"),
    ("tempest logo.jpeg",  "tempest",  "tempest_logo"),
]

def rgb888_to_rgb565_swapped(r, g, b):
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    rgb565 = (r5 << 11) | (g6 << 5) | b5
    return ((rgb565 >> 8) & 0xFF) | ((rgb565 & 0xFF) << 8)

def fit_into(img, target_w, target_h):
    """Resize preservando aspect ratio, centrato su canvas nero target."""
    w, h = img.size
    aspect = w / h
    target_aspect = target_w / target_h
    if aspect > target_aspect:
        new_w = target_w
        new_h = int(target_w / aspect)
    else:
        new_h = target_h
        new_w = int(target_h * aspect)
    resized = img.resize((new_w, new_h), Image.LANCZOS)
    canvas = Image.new('RGB', (target_w, target_h), (0, 0, 0))
    canvas.paste(resized, ((target_w - new_w) // 2, (target_h - new_h) // 2))
    return canvas

def write_header(path, var_name, pixels):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write("// Auto-generated by convert_arcade_logos.py\n")
        f.write(f"// {LOGO_W}x{LOGO_H} RGB565 byte-swap (ESP32 SPI BE), RAW format\n")
        f.write(f"#define {var_name.upper()}_W {LOGO_W}\n")
        f.write(f"#define {var_name.upper()}_H {LOGO_H}\n")
        f.write(f"const unsigned short {var_name}[{LOGO_W}*{LOGO_H}] PROGMEM = {{\n")
        for i in range(0, len(pixels), 12):
            chunk = pixels[i:i+12]
            f.write("  " + ", ".join(f"0x{p:04X}" for p in chunk) + ",\n")
        f.write("};\n")
    print(f"  wrote {path}  ({len(pixels)} px = {len(pixels)*2} bytes)")

def convert(src_name, machine_dir, var_name):
    src_path = os.path.join(LOGOS_DIR, src_name)
    dst_path = os.path.join(OUT_BASE, machine_dir, f"{var_name}.h")
    print(f"[{var_name}] {src_name}")
    img = Image.open(src_path).convert('RGB')
    print(f"  source: {img.size}")
    canvas = fit_into(img, LOGO_W, LOGO_H)
    pixels = [rgb888_to_rgb565_swapped(r, g, b) for (r, g, b) in canvas.getdata()]
    write_header(dst_path, var_name, pixels)

if __name__ == '__main__':
    for src, machine, var in LOGOS:
        convert(src, machine, var)
    print("Done!")
